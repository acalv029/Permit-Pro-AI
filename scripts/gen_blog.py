#!/usr/bin/env python3
"""Flo Permit blog generator.

Run from the repo root:
    python scripts/gen_blog.py

Reads:   blog/posts/*.md
Writes:  frontend/public/blog/*.html (one page per post, plus /blog/ index)
         and refreshes frontend/public/sitemap.xml (by re-running gen_seo_pages.py)

Post format: a front matter block, then markdown.

    ---
    title: Page headline (the H1, up to 90 characters)
    seo_title: Short <title> tag, 70 characters or fewer (optional if the title is short)
    description: Meta description, 155 characters or fewer
    slug: url-slug                  (optional, defaults to the file name)
    date: 2026-10-01
    updated: 2026-10-01             (optional)
    tags: Notice of Commencement, Broward
    cities: fort-lauderdale, miami  (optional, adds a "Requirements for your city" box)
    permits: fort-lauderdale/roofing (optional, adds permit checklist links)
    status: published               (or draft)
    ---

Supported markdown: ## and ### headings, paragraphs, **bold**, *italic*, `code`, [links](url),
bullet and numbered lists, > callouts (use > [!TIP] for a green one), pipe tables, and a
"## FAQ" section (each ### is a question) which also becomes FAQPage markup.

Publishing rules (so nothing unverified goes live):
  * a post containing "[VERIFY" is never published; it is listed in the build report
  * status: draft is never published
  * every internal link must point at a page that exists, or the build fails
Use --include-drafts to preview drafts (noindex, not in the sitemap).
"""
